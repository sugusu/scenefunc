def read(p): return json.loads(p.read_text())
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def write(p,x): p.write_text(json.dumps(x,ensure_ascii=False,indent=2)+'\n')


def furniture_mesh(path, width, depth, height, wheeled):
    scene=trimesh.Scene()
    def box(name,size,center,color):
        mesh=trimesh.creation.box(size);mesh.apply_translation(center)
        mesh.visual.face_colors=color;scene.add_geometry(mesh,node_name=name,geom_name=name)
    box('top',[width,depth,.04],[0,0,height-.02],[235,234,228,255])
    for index,(x,y) in enumerate([(x,y) for x in (-width/2+.08,width/2-.08)
                                 for y in (-depth/2+.08,depth/2-.08)]):
        bottom=.08 if wheeled else 0
        legheight=height-.04-bottom
        box('leg_'+str(index),[.04,.04,legheight],[x,y,bottom+legheight/2],[120,125,130,255])
        if wheeled:
            wheel=trimesh.creation.cylinder(radius=.04,height=.035,sections=16)
            wheel.apply_transform(trimesh.transformations.rotation_matrix(np.pi/2,[1,0,0]))
            wheel.apply_translation([x,y,.04]);wheel.visual.face_colors=[40,40,40,255]
            scene.add_geometry(wheel,node_name='wheel_'+str(index),geom_name='wheel_'+str(index))
    scene.export(path)


